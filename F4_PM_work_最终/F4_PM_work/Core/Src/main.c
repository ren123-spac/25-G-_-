/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_USART2_UART_Init();
  MX_USART1_UART_Init();
  H7Link_Init();
  ScreenLink_Init();
  H7Link_SendLine("PING\r\n");
  /* USER CODE BEGIN 2 */

  /*
   * 串口屏最小验证：切换到 Screen0，并向第一个文本控件(ID=1)写入字符 3。
   * 延时用于等待屏幕上电完成；主循环还会周期性重发，避免屏幕启动较慢时漏帧。
   */
  /* The 7-inch HMI boots slower than the MCU. Wait before the first update. */
  HAL_Delay(2000);
  ScreenLink_SetPage(0U);
  HAL_Delay(50);
  ScreenLink_UpdateAll();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  h7_link_tick = HAL_GetTick();
  screen_sync_tick = HAL_GetTick();
  screen_sync_retries = 0U;
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    ScreenLink_Process();
    H7Link_Process();

    if ((HAL_GetTick() - h7_link_tick) >= 1000U)
    {
      H7Link_SendLine("PING\r\n");
      h7_link_tick = HAL_GetTick();
    }

    /* Retry only during startup in case the HMI missed its first frames. */
    if ((screen_sync_retries < 3U) &&
        ((HAL_GetTick() - screen_sync_tick) >= 1000U))
    {
      ScreenLink_SetPage(0U);
      ScreenLink_UpdateAll();
      ++screen_sync_retries;
      screen_sync_tick = HAL_GetTick();
    }

  }
  /* USER CODE END 3 */
}

